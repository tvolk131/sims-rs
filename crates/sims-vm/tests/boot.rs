//! `sims_vm::boot` on a real install, when `SIMS_INSTALL` names one: the
//! Goth house loads and steps one tick at a time to the state `sims boot`
//! reaches.

use sims_sim::Headline;
use sims_vm::boot::{Frames, Lot, StepError};
