//! Direct hot-frame import. No saved-frame reader, constructor defaults, pointer
//! dereference, source-to-pointer inference, or native arena allocation is used.
use crate::{Definition, Frame, ObjectId, Program, Status, Thread, Vm};
use serde::{Deserialize, Deserializer, Serialize};
use std::collections::BTreeMap;

/// Actual object/resource context supplied by the observer. The pointer is
/// metadata, not an address the replacement VM can dereference.
#[derive(Debug, Clone, Serialize, Deserialize, PartialEq, Eq)]
#[serde(deny_unknown_fields)]
pub struct ContextBinding {
    pub object: ObjectId,
    pub definition: Definition,
    pub native_context: u32,
    /// Explicit canonical scheduler lifetime. None is unknown, sufficient only
    /// for stack-byte decoding, never a new target entry or full Thread owner.
    #[serde(deserialize_with = "required")]
    pub registry_lifetime: Option<u32>,
}

/// Each active frame names a supplied context owner explicitly. Identical code
/// sources do not authorize guessing or borrowing another resource's pointer.
#[derive(Debug, Clone, Serialize, Deserialize, PartialEq, Eq)]
#[serde(deny_unknown_fields)]
pub struct RetainedFrame {
    pub frame: Frame,
    pub context_object: ObjectId,
}

/// Native header provenance only. Raw words have one owner: frame_memory.
/// Removing an active frame removes its metadata annotation, not its bytes.
#[derive(Debug, Clone, Serialize, Deserialize, PartialEq, Eq)]
#[serde(deny_unknown_fields)]
pub struct Arena {
    bindings: BTreeMap<ObjectId, ContextBinding>,
    active_contexts: BTreeMap<usize, ObjectId>,
}

// An Option normally accepts an absent serde field as None. All control fields
// below are required evidence, including explicitly known absence.
fn required<'de, D, T>(d: D) -> Result<Option<T>, D::Error>
where
    D: Deserializer<'de>,
    T: Deserialize<'de>,
{
    Option::<T>::deserialize(d)
}

/// Complete non-arena Thread controls supplied independently by the caller.
/// This deliberately has no Default or conversion from a fresh spawned Thread.
#[derive(Debug, Clone, Serialize, Deserialize, PartialEq)]
#[serde(deny_unknown_fields)]
pub struct ThreadControls {
    #[serde(deserialize_with = "required")]
    pub service: Option<crate::lifecycle::ServiceCall>,
    #[serde(deserialize_with = "required")]
    pub dispatch: Option<crate::action::Dispatch>,
    #[serde(deserialize_with = "required")]
    pub autonomy: Option<crate::autonomy::Query>,
    pub find_best: Vec<crate::find_best::Query>,
    pub completed_actions: Vec<(ObjectId, ObjectId, bool, bool, usize)>,
    pub last_result: bool,
    #[serde(deserialize_with = "required")]
    pub callback: Option<crate::CallbackBoundary>,
    #[serde(deserialize_with = "required")]
    pub callback_result: Option<bool>,
    pub check: bool,
    pub interrupted: bool,
    pub status: Status,
}

/// Decoded hot stack/arena only. This does not instantiate a Thread, VM,
/// lifecycle, request counter, scheduler status, or absent control owner.
#[derive(Debug, Clone, Serialize, PartialEq, Eq)]
pub struct RetainedStack {
    stack: Vec<Frame>,
    frame_memory: Vec<Option<i16>>,
    arena: Arena,
}
impl RetainedStack {
    pub fn from_bytes(
        p: &Program,
        raw_arena: &[u8],
        frames: Vec<RetainedFrame>,
        bindings: Vec<ContextBinding>,
    ) -> Result<Self, String> {
        if raw_arena.is_empty()
            || raw_arena.len() % 8 != 0
            || raw_arena.len() / 2 > crate::MAX_STACK * 520
        {
            return Err("invalid retained frame arena extent".into());
        }
        let mut by_object = BTreeMap::new();
        for binding in bindings {
            let id = binding.object;
            if by_object.insert(id, binding).is_some() {
                return Err("duplicate retained frame context object".into());
            }
        }
        let mut active_contexts = BTreeMap::new();
        let mut stack = Vec::with_capacity(frames.len());
        for retained in frames {
            if active_contexts
                .insert(retained.frame.storage_offset, retained.context_object)
                .is_some()
            {
                return Err("duplicate retained active frame offset".into());
            }
            stack.push(retained.frame);
        }
        let retained = Self {
            stack,
            frame_memory: raw_arena
                .chunks_exact(2)
                .map(|b| Some(i16::from_le_bytes([b[0], b[1]])))
                .collect(),
            arena: Arena {
                bindings: by_object,
                active_contexts,
            },
        };
        validate_storage(p, &retained.stack, &retained.frame_memory, &retained.arena)?;
        // Initial raw header and values must be observed, not regenerated by a
        // saved reader. Dynamic Frame overlays may differ only after execution.
        for f in &retained.stack {
            let mut header = crate::frame_header(f);
            let pointer = header_context(&retained.arena, f)?;
            header[6] = Some(pointer as i16);
            header[7] = Some((pointer >> 16) as i16);
            if retained.frame_memory[f.storage_offset..f.storage_offset + 8] != header {
                return Err("retained raw frame header disagrees with active frame".into());
            }
            for (i, value) in f.args.iter().chain(&f.locals).enumerate() {
                if retained.frame_memory[f.storage_offset + 8 + i] != Some(*value) {
                    return Err("retained raw argument/local disagrees with active frame".into());
                }
            }
        }
        Ok(retained)
    }
    pub fn frames(&self) -> &[Frame] {
        &self.stack
    }
    pub fn raw_bytes(&self) -> Vec<u8> {
        self.frame_memory
            .iter()
            .flat_map(|v| v.unwrap().to_le_bytes())
            .collect()
    }
    /// Build a source-bound status explicitly. This supplies no Thread controls:
    /// service/reply/cancellation/absence values still belong to the importer.
    pub fn native_suspension(
        &self,
        p: &Program,
        evidence: crate::native_suspension::Evidence,
    ) -> Result<crate::native_suspension::Owner, String> {
        let binding = native_ordinary_binding(p, &self.stack, &self.arena)?;
        crate::native_suspension::Owner::new(evidence, binding, &self.stack)
    }
    /// Broader completed-registry owner with typed Sleep/person-polling leaf,
    /// actual Tick dispatch and explicit retained-source absence/Init policy.
    /// This does not authenticate the external native closure or Character host.
    pub fn native_registry_reentry(
        &self,
        p: &Program,
        world: &crate::World,
        capture_tick: u64,
        evidence: crate::native_registry_reentry::Evidence,
        adapter: crate::native_registry_reentry::AdapterOwnership,
    ) -> Result<crate::native_registry_reentry::Owner, String> {
        let binding = registry_binding_parts(&self.stack, &self.arena)?;
        crate::native_registry_reentry::Owner::new(
            p, world, capture_tick, evidence, adapter, binding, &self.stack,
        )
    }
    /// Narrow ordinary/non-group completed-registry owner. Existing serialized
    /// evidence and controls retain their original contract.
    pub fn registry_suspension(
        &self,
        p: &Program,
        world: &crate::World,
        capture_tick: u64,
        token: crate::registry_suspension::Token,
        adapter: crate::registry_suspension::AdapterOwnership,
    ) -> Result<crate::registry_suspension::Owner, String> {
        let binding = registry_binding_parts(&self.stack, &self.arena)?;
        crate::registry_suspension::Owner::new(
            p,
            world,
            capture_tick,
            token,
            adapter,
            binding,
            &self.stack,
        )
    }
    pub fn into_thread(self, p: &Program, controls: ThreadControls) -> Result<Thread, String> {
        let t = Thread {
            service: controls.service,
            dispatch: controls.dispatch,
            autonomy: controls.autonomy,
            find_best: controls.find_best,
            completed_actions: controls.completed_actions,
            last_result: controls.last_result,
            callback: controls.callback,
            callback_result: controls.callback_result,
            stack: self.stack,
            frame_memory: self.frame_memory,
            retained_frame_arena: Some(self.arena),
            check: controls.check,
            interrupted: controls.interrupted,
            status: controls.status,
        };
        validate(p, &t)?;
        Ok(t)
    }
}
impl Thread {
    /// Import complete observed bytes/frames/controls without modifying a VM or
    /// thread/request counters. Full VM registration remains a separate owner.
    pub fn from_retained_frames(
        p: &Program,
        raw_arena: &[u8],
        frames: Vec<RetainedFrame>,
        controls: ThreadControls,
        bindings: Vec<ContextBinding>,
    ) -> Result<Self, String> {
        RetainedStack::from_bytes(p, raw_arena, frames, bindings)?.into_thread(p, controls)
    }
}

fn validate_storage(
    p: &Program,
    stack: &[Frame],
    memory: &[Option<i16>],
    arena: &Arena,
) -> Result<(), String> {
    if memory.is_empty()
        || memory.len() % 4 != 0
        || memory.len() > crate::MAX_STACK * 520
        || memory.iter().any(Option::is_none)
        || stack.len() > crate::MAX_STACK
        || arena.active_contexts.len() != stack.len()
    {
        return Err("invalid retained frame arena shape".into());
    }
    let mut pointers = BTreeMap::new();
    for (&object, binding) in &arena.bindings {
        if object <= 0
            || object != binding.object
            || binding.native_context == 0
            || binding.registry_lifetime == Some(0)
        {
            return Err("invalid retained native context identity".into());
        }
        let words = crate::construction::definition_words(p, &binding.definition)?;
        if binding.definition.guid
            != (u32::from(words[14] as u16) | (u32::from(words[15] as u16) << 16))
            || binding.definition.slots != words[20] as u16
        {
            return Err("retained context immutable definition identity mismatch".into());
        }
        if let Some(previous) = pointers.insert(binding.native_context, &binding.definition)
            && previous != &binding.definition
        {
            return Err("retained context pointer aliases distinct definitions".into());
        }
    }
    let mut end = 0;
    for f in stack {
        let (source, routine) = p.resolve(&f.code_owner, f.location.bhav)?;
        let (argc, locals) = crate::dimensions(routine)?;
        if source != f.location.source
            || f.storage_offset < end
            || f.args.len() != argc
            || f.locals.len() != locals
            || !f.opaque_locals.is_empty()
            || f.location.instruction >= routine.body.instructions.len()
            || f.location.instruction > 0xfa
        {
            return Err("invalid retained active frame/source/dimensions".into());
        }
        end = f
            .storage_offset
            .checked_add(crate::frame_words(argc, locals))
            .ok_or("retained frame offset overflow")?;
        if end > memory.len() {
            return Err("retained frame exceeds captured arena".into());
        }
        let pointer = header_context(arena, f)?;
        if memory.get(f.storage_offset + 6) != Some(&Some(pointer as i16))
            || memory.get(f.storage_offset + 7) != Some(&Some((pointer >> 16) as i16))
        {
            return Err("retained active context raw metadata disagrees".into());
        }
    }
    Ok(())
}

/// Validate the optional owner without reconstructing/normalizing arena bytes.
/// This supplements, rather than replaces, full VM Snapshot ownership checks.
pub fn validate(p: &Program, t: &Thread) -> Result<(), String> {
    let Some(arena) = &t.retained_frame_arena else {
        return crate::native_suspension::validate(p, t);
    };
    validate_storage(p, &t.stack, &t.frame_memory, arena)?;
    for object in arena.active_contexts.values() {
        if arena.bindings[object].registry_lifetime.is_none() {
            return Err("retained active context registry lifetime is unknown".into());
        }
    }
    if t.stack.is_empty() != matches!(t.status, Status::Returned(_)) {
        return Err("invalid retained frame control/status shape".into());
    }
    let mut offset = 0;
    for (depth, f) in t.stack.iter().enumerate() {
        if t.callback
            .iter()
            .flat_map(|b| b.chain())
            .any(|b| b.base_depth == depth)
        {
            let sentinel = [
                Some(-1),
                Some(0),
                Some(0),
                Some(0),
                Some(1),
                Some(0),
                Some(0),
                Some(0),
            ];
            if t.frame_memory.get(offset..offset + 8) != Some(sentinel.as_slice()) {
                return Err("retained callback sentinel missing".into());
            }
            offset += 8;
        }
        if f.storage_offset != offset {
            return Err("retained active frame offset/control mismatch".into());
        }
        offset += crate::frame_words(f.args.len(), f.locals.len());
    }
    crate::native_suspension::validate(p, t)
}

/// Restored active contexts must still belong to the captured object lifetime.
/// Stale bindings may remain as provenance, but never authorize a reused ID.
pub(crate) fn validate_world(p: &Program, world: &crate::World, t: &Thread) -> Result<(), String> {
    validate(p, t)?;
    let Some(arena) = &t.retained_frame_arena else {
        return Ok(());
    };
    for object in arena.active_contexts.values() {
        validate_current_binding(world, &arena.bindings[object])?;
    }
    Ok(())
}
pub(crate) fn validate_current_binding(
    world: &crate::World,
    binding: &ContextBinding,
) -> Result<(), String> {
    let lifetime = binding
        .registry_lifetime
        .ok_or("retained native context registry lifetime is unknown")?;
    if world
        .scheduler_storage
        .as_ref()
        .and_then(|s| s.handle(binding.object))
        != Some(lifetime)
    {
        return Err("target retained native context registry lifetime mismatch".into());
    }
    if world
        .objects
        .get(&binding.object)
        .and_then(|o| o.definition.as_ref())
        != Some(&binding.definition)
    {
        return Err("target retained native context/definition mismatch".into());
    }
    Ok(())
}

/// No captured extension/allocator bytes are guessed as zero.
pub(crate) fn ensure_capacity(t: &Thread, end: usize) -> Result<(), String> {
    if t.retained_frame_arena.is_some() && end > t.frame_memory.len() {
        return Err("retained frame arena growth needs native allocation ownership".into());
    }
    Ok(())
}

fn header_context(arena: &Arena, f: &Frame) -> Result<u32, String> {
    let object = arena
        .active_contexts
        .get(&f.storage_offset)
        .ok_or("retained frame context binding absent")?;
    let binding = arena
        .bindings
        .get(object)
        .ok_or("retained native resource context absent")?;
    if binding.definition.source != f.code_owner {
        return Err("retained frame private context/source mismatch".into());
    }
    Ok(binding.native_context)
}
pub(crate) fn context_word(t: &Thread, f: &Frame) -> Result<Option<u32>, String> {
    t.retained_frame_arena
        .as_ref()
        .map(|arena| header_context(arena, f))
        .transpose()
}

pub(crate) fn inherited_context(t: &Thread, f: &Frame) -> Result<Option<ObjectId>, String> {
    context_word(t, f)?;
    Ok(t.retained_frame_arena
        .as_ref()
        .map(|a| a.active_contexts[&f.storage_offset]))
}

impl Vm {
    pub(crate) fn retained_entry_context(
        &self,
        t: &Thread,
        object: ObjectId,
        owner: &str,
    ) -> Result<Option<ObjectId>, String> {
        let Some(arena) = &t.retained_frame_arena else {
            return Ok(None);
        };
        let binding = arena
            .bindings
            .get(&object)
            .ok_or("target native resource context is unobserved")?;
        if binding.definition.source != owner {
            return Err("target retained native context/definition mismatch".into());
        }
        validate_current_binding(&self.world, binding)?;
        Ok(Some(object))
    }
}

pub(crate) fn finish_entry(
    t: &mut Thread,
    frame: Frame,
    context: Option<ObjectId>,
) -> Result<(), String> {
    finish_entry_with(t, frame, context, |_| {})
}

pub(crate) fn finish_entry_with(
    t: &mut Thread,
    frame: Frame,
    context: Option<ObjectId>,
    mut entered: impl FnMut(&Thread),
) -> Result<(), String> {
    ensure_capacity(
        t,
        frame.storage_offset + crate::frame_words(frame.args.len(), frame.locals.len()),
    )?;
    if let Some(arena) = &t.retained_frame_arena {
        let binding = context
            .and_then(|object| arena.bindings.get(&object))
            .ok_or("new retained frame context unavailable")?;
        if binding.definition.source != frame.code_owner {
            return Err("new retained frame context/source mismatch".into());
        }
    }
    let offset = frame.storage_offset;
    t.stack.push(frame);
    entered(t);
    if let Some(arena) = &mut t.retained_frame_arena {
        arena.active_contexts.insert(offset, context.unwrap());
        crate::save_frame_storage(t)?;
    }
    Ok(())
}

pub(crate) fn remove_frame(t: &mut Thread, offset: usize) {
    if let Some(arena) = &mut t.retained_frame_arena {
        arena.active_contexts.remove(&offset);
    }
}

pub(crate) fn reset_contexts(t: &mut Thread) {
    if let Some(arena) = &mut t.retained_frame_arena {
        arena.active_contexts.clear();
    }
}

