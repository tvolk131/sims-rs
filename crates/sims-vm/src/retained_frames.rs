// A bounded source-derived ordinary shape. This is not a conversion from a
// saved-frame reader and does not infer complete absence of host continuations.
fn registry_binding_parts(frames: &[Frame], arena: &Arena) -> Result<ContextBinding, String> {
    let object = frames
        .first()
        .ok_or("completed registry ordinary stack absent")?
        .caller;
    let binding = arena
        .bindings
        .get(&object)
        .ok_or("completed registry private context absent")?;
    if binding.registry_lifetime.is_none()
        || frames.iter().any(|f| {
            f.caller != object
                || f.callee != object
                || f.continuation != 0
                || f.action_target.is_some()
                || f.action_icon
                || f.code_owner != binding.definition.source
                || arena.active_contexts.get(&f.storage_offset) != Some(&object)
        })
    {
        return Err("completed registry ordinary context/continuation differs".into());
    }
    Ok(binding.clone())
}
pub(crate) fn registry_binding(t: &Thread, depth: usize) -> Result<ContextBinding, String> {
    registry_binding_parts(
        t.stack
            .get(..depth)
            .ok_or("completed registry parent depth exceeds stack")?,
        t.retained_frame_arena
            .as_ref()
            .ok_or("completed registry retained arena absent")?,
    )
}

fn native_ordinary_binding(
    p: &Program,
    frames: &[Frame],
    arena: &Arena,
) -> Result<ContextBinding, String> {
    if frames.len() != 2 {
        return Err("native suspension requires the retained ordinary Main/Sleep shape".into());
    }
    let root = &frames[0];
    let idle = &frames[1];
    let object = root.caller;
    let binding = arena
        .bindings
        .get(&object)
        .ok_or("native suspension context absent")?;
    if binding.registry_lifetime.is_none()
        || [root, idle].iter().any(|f| {
            f.caller != object
                || f.callee != object
                || f.continuation != 0
                || f.action_target.is_some()
                || f.action_icon
                || f.code_owner != binding.definition.source
                || arena.active_contexts.get(&f.storage_offset) != Some(&object)
        })
        || root.storage_offset != 0
        || idle.storage_offset != crate::frame_words(root.args.len(), root.locals.len())
    {
        return Err("native suspension ordinary context/layout mismatch".into());
    }
    let module = p
        .modules
        .get(&binding.definition.source)
        .ok_or("native suspension module absent")?;
    let words = module
        .object_definition_words
        .get(&binding.definition.object)
        .ok_or("native suspension definition absent")?;
    let main = module
        .object_functions
        .get(&binding.definition.object)
        .and_then(|v| v.get(1))
        .ok_or("native suspension Main binding absent")?
        .action;
    let (_, parent) = p.resolve(&root.code_owner, root.location.bhav)?;
    let (_, child) = p.resolve(&idle.code_owner, idle.location.bhav)?;
    let call = parent
        .body
        .instructions
        .get(root.location.instruction)
        .ok_or("native suspension Main instruction absent")?;
    let sleep = child
        .body
        .instructions
        .get(idle.location.instruction)
        .ok_or("native suspension Sleep instruction absent")?;
    if words.get(9) != Some(&4)
        || main == 0
        || root.location.bhav != main
        || call.opcode != idle.location.bhav
        || call.opcode < 256
        || call.opcode & 0x8000 != 0
        || sleep.opcode != 0
        || root.location.source != root.code_owner
        || idle.location.source != p.globals
        || idle.location.bhav != 280
        || usize::try_from(i16::from_le_bytes([sleep.operands[0], sleep.operands[1]]))
            .ok()
            .is_none_or(|i| i >= idle.args.len())
    {
        return Err("native suspension source/ordinary Sleep binding mismatch".into());
    }
    Ok(binding.clone())
}

pub(crate) fn native_binding(
    p: &Program,
    t: &Thread,
    depth: usize,
) -> Result<ContextBinding, String> {
    let arena = t
        .retained_frame_arena
        .as_ref()
        .ok_or("native suspension lacks retained arena")?;
    let frames = t
        .stack
        .get(..depth)
        .ok_or("native suspension parent depth exceeds stack")?;
    native_ordinary_binding(p, frames, arena)
}

pub(crate) fn native_binding_current(
    world: &crate::World,
    t: &Thread,
    binding: &ContextBinding,
) -> Result<(), String> {
    let arena = t
        .retained_frame_arena
        .as_ref()
        .ok_or("native suspension lacks retained arena")?;
    if arena.bindings.get(&binding.object) != Some(binding) {
        return Err("native suspension retained context changed".into());
    }
    validate_current_binding(world, binding)
}
