/// Whether the `.air` parser gives `word` a meaning of its own.
pub(crate) fn is_air_word(word: &str) -> bool {
    AIR_WORDS.binary_search(&word).is_ok()
}

#[cfg(test)]
mod tests {
    use super::*;

    /// The list is sorted and covers every word the `.air` parser matches on, so a word added to
    /// the parser cannot silently become a `const` substitution site.
    #[test]
    fn covers_every_parser_word() {
        assert!(
            AIR_WORDS.windows(2).all(|w| w[0] < w[1]),
            "AIR_WORDS must stay sorted"
        );
        let src = include_str!("../parser.rs");
        let mut missing = Vec::new();
        for (i, _) in src.match_indices('"') {
            let rest = &src[i + 1..];
            let Some(end) = rest.find('"') else { break };
            let word = &rest[..end];
            if word.is_empty()
                || !word.starts_with(|c: char| c.is_ascii_lowercase() || c == '_')
                || !word
                    .chars()
                    .all(|c| c.is_ascii_lowercase() || c.is_ascii_digit() || c == '_')
            {
                continue;
            }
            let after = rest[end + 1..].trim_start();
            let before = src[..i].trim_end();
            let matched =
                after.starts_with("=>") || after.starts_with('|') || before.ends_with("s ==");
            if matched && !is_air_word(word) {
                missing.push(word.to_owned());
            }
        }
        missing.sort();
        missing.dedup();
        assert!(missing.is_empty(), "add to AIR_WORDS: {missing:?}");
    }
}
