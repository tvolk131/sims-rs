    fn expr(dst: u8, index: i16, src: u8, value: i16, next: u8) -> Instruction {
        let mut operands = [0; 8];
        operands[..2].copy_from_slice(&index.to_le_bytes());
        operands[2..4].copy_from_slice(&value.to_le_bytes());
        operands[5..].copy_from_slice(&[5, dst, src]);
        Instruction {
            opcode: 2,
            on_true: next,
            on_false: 253,
            operands,
        }
    }
    fn routine(instructions: Vec<Instruction>) -> Routine {
        Routine {
            name: "synthetic callback".into(),
            body: Behavior {
                format: 0x8002,
                kind: 0,
                args: 4,
                locals: 0,
                instructions,
            },
        }
    }
