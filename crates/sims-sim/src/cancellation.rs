//! Function 4 runs synchronously on the cancelled target's frame arena
//! (0x422d46 -> 0x4749b5). Its result is discarded by the queue operation.
use crate::{Simulation, Step, StepStop};
use serde::{Deserialize, Serialize};
use sims_vm::{Program, Start, Status, ThreadId, action::Callback};
#[derive(Debug, Clone, Serialize, Deserialize, PartialEq, Eq)]
pub struct Execution {
    pub callback: Callback,
    pub thread: ThreadId,
    pub depth: usize,
    pub owner: String,
    pub bhav: u16,
    /// Callbacks already waiting behind this one are sequential work, not
    /// reentrant callbacks generated by the running tree.
    pub backlog: std::collections::VecDeque<Callback>,
}

