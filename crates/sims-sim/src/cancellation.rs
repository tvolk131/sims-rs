impl Simulation {
    pub(crate) fn drive_cancellation(
        &mut self,
        p: &Program,
        remaining: &mut usize,
        step: &mut Step,
    ) -> Result<bool, String> {
        loop {
            if self.cancellation.is_none() {
                let Some((callback, owner, bhav)) = self.vm.next_action_callback(p)? else {
                    return Ok(true);
                };
                let thread = *self
                    .vm
                    .object_threads
                    .get(&callback.object)
                    .ok_or("cancellation target has no native thread")?;
                if self.vm.threads[&thread].callback.is_some() {
                    return Err(
                        "reentrant cancellation callback on an active callback is unsupported"
                            .into(),
                    );
                }
                let depth = self.vm.threads[&thread].stack.len();
                let args = self.vm.world.objects[&callback.object].temps.to_vec();
                self.vm.begin_immediate_callback(
                    p,
                    thread,
                    Start {
                        owner: &owner,
                        bhav,
                        caller: callback.object,
                        callee: callback.object,
                        stack_object: callback.stack_object,
                        args,
                        check: true,
                    },
                )?;
                self.vm
                    .world
                    .actions
                    .as_mut()
                    .unwrap()
                    .callbacks
                    .pop_front();
                self.cancellation = Some(Execution {
                    callback,
                    thread,
                    depth,
                    owner,
                    bhav,
                    backlog: self.vm.world.actions.as_ref().unwrap().callbacks.clone(),
                });
            }
            let e = self.cancellation.clone().unwrap();
            let t = &self.vm.threads[&e.thread];
            if t.callback.is_none() {
                t.callback_result
                    .ok_or("cancellation callback result missing")?;
                self.cancellation = None;
                continue;
            }
            if self.vm.world.actions.as_ref().unwrap().callbacks != e.backlog {
                return Err(
                    "nested cancellation callbacks require a stacked host continuation".into(),
                );
            }
            if *remaining == 0 {
                return Ok(false);
            }
            self.sync_spatial_world();
            match self.vm.threads[&e.thread].status.clone() {
                Status::Ready => {
                    // The original wrapper invokes each callback synchronously.
                    // Pending siblings must not stop its VM slice at the normal
                    // host callback-dispatch boundary. Preserve any newly queued
                    // work so the explicit reentrancy check can reject it.
                    let mut backlog =
                        std::mem::take(&mut self.vm.world.actions.as_mut().unwrap().callbacks);
                    let result = self.vm.run_slice(p, e.thread, *remaining);
                    backlog.append(&mut self.vm.world.actions.as_mut().unwrap().callbacks);
                    self.vm.world.actions.as_mut().unwrap().callbacks = backlog;
                    let r = result?;
                    *remaining -= r.trace.len();
                    step.trace.extend(r.trace);
                    self.publish_budget_statistics();
                }
                Status::AwaitingCreation(r) => {
                    if !self.service_creation(p, e.thread, r, remaining, step)? {
                        return Ok(false);
                    }
                }
                Status::AwaitingRemoval(r) => {
                    if !self.service_removal(p, e.thread, &r, remaining, step)? {
                        return Ok(false);
                    }
                }
                Status::AwaitingPlacement(r) => {
                    self.service_find_location(p, e.thread, &r, &mut step.events)?
                }
                Status::AwaitingTransfer(r) => {
                    self.service_transfer(p, e.thread, &r, &mut step.events)?;
                    self.sync_carry(p)?;
                }
                Status::Faulted(f) => {
                    return Err(format!(
                        "action cancellation callback failed: {}",
                        f.message
                    ));
                }
                s => {
                    return Err(format!(
                        "action cancellation callback yielded (native error 0x44f): {s:?}"
                    ));
                }
            }
        }
    }
    pub(crate) fn flush_action_callbacks(&mut self, p: &Program) -> Result<(), String> {
        let mut step = Step {
            stop: StepStop::Waiting,
            trace: vec![],
            events: vec![],
        };
        if !self.drive_cancellation(p, &mut 100000, &mut step)? {
            return Err("action cancellation exceeds command instruction budget".into());
        }
        self.sync_spatial_world();
        Ok(())
    }
    pub(crate) fn validate_cancellation(&self, p: &Program) -> Result<(), String> {
        let Some(e) = &self.cancellation else {
            return Ok(());
        };
        let t = self
            .vm
            .threads
            .get(&e.thread)
            .ok_or("saved cancellation thread missing")?;
        let o = self
            .vm
            .world
            .objects
            .get(&e.callback.object)
            .ok_or("saved cancellation target missing")?;
        let d = o
            .definition
            .as_ref()
            .ok_or("saved cancellation definition missing")?;
        let f = t
            .stack
            .get(e.depth)
            .ok_or("saved cancellation frame missing")?;
        if e.callback.function != 4
            || self
                .vm
                .world
                .actions
                .as_ref()
                .is_none_or(|a| a.callbacks != e.backlog)
            || self.vm.object_threads.get(&e.callback.object) != Some(&e.thread)
            || d.source != e.owner
            || p.modules[&e.owner].object_functions[&d.object][4].action != e.bhav
            || f.caller != e.callback.object
            || f.callee != e.callback.object
            || f.code_owner != e.owner
            || f.location.bhav != e.bhav
            || t.callback
                .as_ref()
                .is_none_or(|b| !b.chain().any(|b| b.external && b.base_depth == e.depth))
            || self
                .vm
                .world
                .actions
                .as_ref()
                .is_none_or(|a| !a.actors.contains_key(&e.callback.stack_object))
        {
            return Err("invalid saved cancellation callback binding".into());
        }
        Ok(())
    }
}
